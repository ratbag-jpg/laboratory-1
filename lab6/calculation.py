#Імпортуємо декоратор make_positive з файлу decorator
#Завдяки цьому можемо використовувати його в цьому файлі

@make_positive
#Застосовуємо декоратор до наступної функції
#Тепер перед поверненням результату функція проходитиме перевірку декоратора
def calculate(a, b): #Створюємо функцію calculate. Вона приймає два числа: a і b
    return a - b #Віднімаємо друге число від першого. Повертаємо результат