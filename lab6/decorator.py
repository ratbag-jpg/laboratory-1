def make_positive(func):
    #make_positive — назва нашого декоратора
    #func — функція, яку ми будемо декорувати (обгортати)
    def wrapper(*args, **kwargs):
        #*args — дозволяє передавати будь-яку кількість звичайних аргументів
        #**kwargs — дозволяє передавати аргументи за назвою
        result = func(*args, **kwargs)
        #Викликаємо початкову функцію func
        #Передаємо їй усі отримані аргументи
        #Результат записуємо у змінну result

        if result < 0: #if — перевірка умови. Перевіряємо, чи результат менший за нуль
            result *= -1 #Якщо число від'ємне, множимо його на -1 Наприклад: -5 * -1 = 5

        return result #Повертаємо результат після перевірки

    return wrapper #Повертаємо функцію-обгортку, яка замінить початкову функцію